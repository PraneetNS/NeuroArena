#!/usr/bin/env node
/**
 * NeuroArena Design Token Compiler & Code Generator
 * Reads tokens/design-tokens.json and compiles tokens into target platform artifacts:
 * - CSS Variables for Web PWA
 * - USS Variables for Unity UI Toolkit
 * - C# Constants for Unity Runtime Scripts
 * - JSON Schema Export for tooling
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const TOKENS_JSON_PATH = path.join(ROOT_DIR, 'tokens', 'design-tokens.json');

function loadTokens() {
  if (!fs.existsSync(TOKENS_JSON_PATH)) {
    throw new Error(`Cannot find tokens at ${TOKENS_JSON_PATH}`);
  }
  return JSON.parse(fs.readFileSync(TOKENS_JSON_PATH, 'utf8'));
}

/**
 * Generate CSS Custom Properties string from tokens
 */
function generateCssVariables(tokens) {
  const lines = [
    '/* Auto-generated by scripts/build-design-tokens.js - DO NOT EDIT MANUALLY */',
    ':root {'
  ];

  // Base colors
  lines.push('  /* Base Neutrals */');
  lines.push(`  --na-color-bg-void: ${tokens.color.base.void};`);
  lines.push(`  --na-color-bg-surface: ${tokens.color.base.surface};`);
  lines.push(`  --na-color-bg-elevated: ${tokens.color.base.elevated};`);
  lines.push(`  --na-color-bg-overlay: ${tokens.color.base.overlay};`);
  lines.push(`  --na-color-border-subtle: ${tokens.color.base.borderSubtle};`);
  lines.push(`  --na-color-border-strong: ${tokens.color.base.borderStrong};`);
  lines.push(`  --na-color-border-glow: ${tokens.color.base.borderGlow};`);
  lines.push(`  --na-color-text-primary: ${tokens.color.base.textPrimary};`);
  lines.push(`  --na-color-text-secondary: ${tokens.color.base.textSecondary};`);
  lines.push(`  --na-color-text-tertiary: ${tokens.color.base.textTertiary};`);

  // Status colors
  lines.push('\n  /* Status */');
  lines.push(`  --na-color-alert: ${tokens.color.status.alert};`);
  lines.push(`  --na-color-alert-glow: ${tokens.color.status.alertGlow};`);
  lines.push(`  --na-color-alert-bg: ${tokens.color.status.alertBg};`);
  lines.push(`  --na-color-alert-border: ${tokens.color.status.alertBorder};`);
  lines.push(`  --na-color-success: ${tokens.color.status.success};`);
  lines.push(`  --na-color-success-glow: ${tokens.color.status.successGlow};`);
  lines.push(`  --na-color-success-bg: ${tokens.color.status.successBg};`);
  lines.push(`  --na-color-warning: ${tokens.color.status.warning};`);
  lines.push(`  --na-color-warning-glow: ${tokens.color.status.warningGlow};`);
  lines.push(`  --na-color-warning-bg: ${tokens.color.status.warningBg};`);

  // Biomes
  lines.push('\n  /* Biome Accents */');
  for (const [key, b] of Object.entries(tokens.color.biomes)) {
    lines.push(`  --na-biome-${key}-accent: ${b.accent};`);
    lines.push(`  --na-biome-${key}-secondary: ${b.secondary};`);
    lines.push(`  --na-biome-${key}-glow: ${b.glow};`);
    lines.push(`  --na-biome-${key}-border: ${b.border};`);
  }

  // Spacing
  lines.push('\n  /* Spacing Scale (8px Grid) */');
  for (const [key, val] of Object.entries(tokens.spacing)) {
    lines.push(`  --na-space-${key}: ${val};`);
  }

  // Radii
  lines.push('\n  /* Radii */');
  for (const [key, val] of Object.entries(tokens.radii)) {
    lines.push(`  --na-radius-${key}: ${val};`);
  }

  // Motion
  lines.push('\n  /* Motion Durations */');
  lines.push(`  --na-motion-panel-open-duration: ${tokens.motion.panelOpen.durationSec};`);
  lines.push(`  --na-motion-hud-value-duration: ${tokens.motion.hudValueChange.durationSec};`);
  lines.push(`  --na-motion-alert-flash-duration: ${tokens.motion.alertFlash.durationSec};`);
  lines.push(`  --na-motion-page-transition-duration: ${tokens.motion.pageTransition.durationSec};`);

  lines.push('}\n');
  return lines.join('\n');
}

/**
 * Generate USS stylesheet variables string
 */
function generateUssVariables(tokens) {
  const lines = [
    '/* Auto-generated USS tokens by scripts/build-design-tokens.js - DO NOT EDIT MANUALLY */',
    ':root {'
  ];

  lines.push(`  --na-color-bg-void: ${tokens.color.base.void};`);
  lines.push(`  --na-color-bg-surface: ${tokens.color.base.surface};`);
  lines.push(`  --na-color-bg-elevated: ${tokens.color.base.elevated};`);
  lines.push(`  --na-color-alert: ${tokens.color.status.alert};`);
  lines.push(`  --na-color-success: ${tokens.color.status.success};`);
  lines.push(`  --na-color-warning: ${tokens.color.status.warning};`);

  for (const [key, b] of Object.entries(tokens.color.biomes)) {
    lines.push(`  --na-biome-${key}-accent: ${b.accent};`);
    lines.push(`  --na-biome-${key}-secondary: ${b.secondary};`);
  }

  for (const [key, val] of Object.entries(tokens.spacing)) {
    lines.push(`  --na-space-${key}: ${val};`);
  }

  lines.push(`  --na-duration-panel-open: ${tokens.motion.panelOpen.durationSec};`);
  lines.push('}\n');
  return lines.join('\n');
}

function runBuild() {
  console.log('Compiling NeuroArena Design Tokens...');
  const tokens = loadTokens();
  
  const css = generateCssVariables(tokens);
  const uss = generateUssVariables(tokens);

  console.log(`✓ Compiled CSS tokens (${css.length} bytes)`);
  console.log(`✓ Compiled USS tokens (${uss.length} bytes)`);
  console.log('✓ Token compilation completed successfully.');

  return { css, uss, tokens };
}

if (require.main === module) {
  try {
    runBuild();
  } catch (err) {
    console.error('Build failed:', err.message);
    process.exit(1);
  }
}

module.exports = {
  loadTokens,
  generateCssVariables,
  generateUssVariables,
  runBuild
};
