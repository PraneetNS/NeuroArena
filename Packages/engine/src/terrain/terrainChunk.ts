/**
 * TerrainChunk: Represents an individual 64m x 64m streamed terrain piece with LOD management.
 */

import * as THREE from 'three/webgpu';

export class TerrainChunk {
  public chunkX: number;
  public chunkZ: number;
  public chunkSize: number;
  public worldCenterX: number;
  public worldCenterZ: number;

  public lod: 0 | 1 | 2 = 2;
  public isPending = false;
  public isReady = false;

  public mesh: THREE.Mesh | null = null;
  public geometry: THREE.BufferGeometry | null = null;

  constructor(chunkX: number, chunkZ: number, chunkSize = 64) {
    this.chunkX = chunkX;
    this.chunkZ = chunkZ;
    this.chunkSize = chunkSize;

    this.worldCenterX = chunkX * chunkSize + chunkSize * 0.5;
    this.worldCenterZ = chunkZ * chunkSize + chunkSize * 0.5;
  }

  public get key(): string {
    return `${this.chunkX}_${this.chunkZ}`;
  }

  public distanceTo(x: number, z: number): number {
    const dx = this.worldCenterX - x;
    const dz = this.worldCenterZ - z;
    return Math.sqrt(dx * dx + dz * dz);
  }

  /**
   * Assigns geometry generated by worker/main thread and attaches to scene.
   */
  public setMesh(
    geometry: THREE.BufferGeometry,
    material: THREE.Material,
    lod: 0 | 1 | 2,
    parent: THREE.Group
  ): void {
    if (this.geometry) {
      this.geometry.dispose();
    }
    if (this.mesh) {
      parent.remove(this.mesh);
    }

    this.geometry = geometry;
    this.lod = lod;
    this.mesh = new THREE.Mesh(geometry, material);
    this.mesh.position.set(this.chunkX * this.chunkSize, 0, this.chunkZ * this.chunkSize);
    this.mesh.castShadow = true;
    this.mesh.receiveShadow = true;

    // Fast bounding box for frustum culling
    this.mesh.geometry.computeBoundingBox();
    this.mesh.geometry.computeBoundingSphere();

    parent.add(this.mesh);
    this.isReady = true;
    this.isPending = false;
  }

  public dispose(parent: THREE.Group): void {
    if (this.mesh) {
      parent.remove(this.mesh);
      this.mesh = null;
    }
    if (this.geometry) {
      this.geometry.dispose();
      this.geometry = null;
    }
    this.isReady = false;
    this.isPending = false;
  }
}
